"""Regenerate catalogue files from document front-matter.

Owns (overwrites) these generated files:
  - runbooks/README.md — catalogue of all runbooks
  - docs/index.md      — index of the docs/ tree

Output is deterministic (no timestamps), so CI can detect uncommitted drift with
``git diff --exit-code``.

Usage:
    python -m tools.render
"""

from __future__ import annotations

from tools import REPO_ROOT, iter_markdown_files, read_front_matter, relative

GENERATED = "<!-- GENERATED by tools/render.py — do not edit by hand; run `make render`. -->"

_OTHER_AREAS = [
    ("Runbooks", "../runbooks/README.md"),
    ("On-call", "../on-call/README.md"),
    ("Continuity (BCP/DR)", "../continuity/README.md"),
    ("Incidents", "../incidents/README.md"),
]


def _runbook_rows() -> list[dict]:
    rows = []
    for path in iter_markdown_files():
        rel = relative(path)
        if not rel.startswith("runbooks/") or rel == "runbooks/README.md":
            continue
        if "_templates/" in rel:
            continue
        front_matter, _ = read_front_matter(path)
        if not front_matter:
            continue
        record = dict(front_matter)
        record["_target"] = rel[len("runbooks/"):]
        rows.append(record)
    rows.sort(key=lambda r: (str(r.get("category", "")), str(r.get("id", ""))))
    return rows


def _runbooks_readme() -> str:
    lines = [
        GENERATED,
        "",
        "# Runbooks",
        "",
        "Catalogue of operational runbooks. Do not edit by hand; run `make render`.",
        "",
        "Add one from [`_templates/runbook-template.md`](_templates/runbook-template.md); see the "
        "[`../docs/governance/runbook-standard.md`](../docs/governance/runbook-standard.md).",
        "",
        "| ID | Title | Category | Severity | Status | RTO | RPO |",
        "|----|-------|----------|----------|--------|-----|-----|",
    ]
    for row in _runbook_rows():
        cells = [
            str(row.get("id", "")),
            f"[{row.get('title', '')}]({row['_target']})",
            str(row.get("category", "")),
            str(row.get("severity", "—")),
            str(row.get("status", "")),
            str(row.get("rto", "—")),
            str(row.get("rpo", "—")),
        ]
        lines.append("| " + " | ".join(cells) + " |")
    lines.append("")
    return "\n".join(lines)


def _title_for(rel: str, front_matter: dict | None) -> str:
    if front_matter and front_matter.get("title"):
        return str(front_matter["title"])
    name = rel.rsplit("/", 1)[-1]
    if name.endswith(".md"):
        name = name[:-3]
    return name.replace("-", " ").replace("_", " ").strip().title()


def _docs_index() -> str:
    groups: dict[str, list[tuple[str, str]]] = {}
    for path in iter_markdown_files():
        rel = relative(path)
        if not rel.startswith("docs/") or rel == "docs/index.md":
            continue
        if "_templates/" in rel:
            continue
        front_matter, _ = read_front_matter(path)
        parts = rel.split("/")
        group = parts[1] if len(parts) > 2 else "general"
        target = rel[len("docs/"):]
        groups.setdefault(group, []).append((_title_for(rel, front_matter), target))

    lines = [
        GENERATED,
        "",
        "# Documentation Index",
        "",
        "Governance, onboarding, and compliance documents. Do not edit by hand; run `make render`.",
        "",
    ]
    for group in sorted(groups):
        lines.append(f"## {group.replace('-', ' ').title()}")
        lines.append("")
        for title, target in sorted(groups[group], key=lambda item: item[1]):
            lines.append(f"- [{title}]({target})")
        lines.append("")
    lines.append("## Other areas")
    lines.append("")
    for label, target in _OTHER_AREAS:
        lines.append(f"- [{label}]({target})")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    """Entry point. Returns a process exit code."""
    _ = argv
    runbooks_path = REPO_ROOT / "runbooks" / "README.md"
    docs_path = REPO_ROOT / "docs" / "index.md"
    runbooks_path.write_text(_runbooks_readme(), encoding="utf-8")
    docs_path.write_text(_docs_index(), encoding="utf-8")
    print(f"Rendered {relative(runbooks_path)} and {relative(docs_path)}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
