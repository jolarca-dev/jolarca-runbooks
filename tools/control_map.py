"""Regenerate docs/compliance/control-mapping.md from front-matter ``related_controls``.

The mapping is generated, never hand-maintained, so it cannot drift from the documents. Exits
non-zero if a required control has no supporting artifact — a coverage gap an auditor would find.
Output is deterministic (no timestamps) so CI can detect drift with ``git diff --exit-code``.

Usage:
    python -m tools.control_map
"""

from __future__ import annotations

from collections import defaultdict

from tools import REPO_ROOT, iter_markdown_files, read_front_matter, relative

OUTPUT = REPO_ROOT / "docs" / "compliance" / "control-mapping.md"
GENERATED = (
    "<!-- GENERATED by tools/control_map.py — do not edit by hand; run `make control-map`. -->"
)

FRAMEWORKS = {"ISO27001": "ISO/IEC 27001:2022", "SOC2": "SOC 2", "GDPR": "GDPR"}

REQUIRED_CONTROLS = [
    "ISO27001:A.5.24",
    "ISO27001:A.5.25",
    "ISO27001:A.5.26",
    "ISO27001:A.5.27",
    "ISO27001:A.5.28",
    "ISO27001:A.5.29",
    "SOC2:CC7.3",
    "SOC2:CC7.4",
    "SOC2:CC7.5",
    "SOC2:CC9.1",
    "GDPR:Art.32",
]


def _artifacts() -> list[tuple[str, str, str]]:
    """Return (control, title, repo-relative path) triples for every declared control."""
    triples = []
    for path in iter_markdown_files():
        rel = relative(path)
        if rel.startswith("tests/") or "_templates/" in rel:
            continue
        front_matter, _ = read_front_matter(path)
        if not front_matter:
            continue
        title = str(front_matter.get("title", rel))
        for control in front_matter.get("related_controls") or []:
            triples.append((str(control), title, rel))
    return triples


def _split(control: str) -> tuple[str, str]:
    framework, _, name = control.partition(":")
    return FRAMEWORKS.get(framework, framework), name


def main(argv: list[str] | None = None) -> int:
    """Entry point. Returns a process exit code."""
    _ = argv
    by_control: dict[str, list[tuple[str, str]]] = defaultdict(list)
    for control, title, rel in _artifacts():
        by_control[control].append((title, rel))

    lines = [
        GENERATED,
        "",
        "# Control Mapping",
        "",
        "Artifact-to-control mapping generated from front-matter `related_controls`. Do not edit "
        "by hand; run `make control-map`.",
        "",
        "## Required-control coverage",
        "",
        "| Control | Framework | Artifacts | Status |",
        "|---------|-----------|:---------:|--------|",
    ]
    gaps = []
    for control in REQUIRED_CONTROLS:
        framework, name = _split(control)
        count = len(by_control.get(control, []))
        if count == 0:
            gaps.append(control)
        status = "Covered" if count else "**GAP**"
        lines.append(f"| {name} | {framework} | {count} | {status} |")

    lines += ["", "## Artifacts by control", ""]
    for control in sorted(by_control):
        framework, name = _split(control)
        lines.append(f"### {framework} — {name}")
        lines.append("")
        for title, rel in sorted(by_control[control], key=lambda item: item[1]):
            lines.append(f"- [{title}](../../{rel})")
        lines.append("")

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")

    if gaps:
        print(
            f"Control map written to {relative(OUTPUT)}, but {len(gaps)} required control(s) "
            f"have no artifact: {', '.join(gaps)}"
        )
        return 1
    print(f"Control map written to {relative(OUTPUT)}; all required controls covered.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
